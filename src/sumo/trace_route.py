"""Trace-driven SUMO route generation and export.

Converts real-world CV tracking logs (ZoneEvents, LaneCounter departure records, or SQLite telemetry)
into reproducible SUMO route files (.rou.xml) for deterministic simulation replays.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any, Iterable, List, Optional, Sequence

from src import config
from src.sumo.injection import (
    APPROACH_EDGES,
    APPROACH_TURNS,
    CATALOG_VEHICLE_TYPES,
    normalize_approach,
)

logger = logging.getLogger(__name__)


def generate_trace_routes_xml(
    departures: Sequence[dict[str, Any]],
    duration: Optional[float] = None,
) -> str:
    """Generate SUMO XML string containing vehicle types, routes, and individual vehicle departures.

    Parameters
    ----------
    departures : Sequence[dict[str, Any]]
        List of departure records containing:
        - 'depart_time' (float, seconds from start)
        - 'approach' (str, e.g. 'North', 'N', 'East')
        - 'class_name' (str, vehicle class e.g. 'car', 'bus')
        - 'track_id' (int | str, tracking ID)
        - 'turn' (optional str, 'through' or 'left')
    duration : Optional[float]
        Total episode duration in seconds (optional metadata).
    """
    lines: list[str] = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- Generated by Autonomous ITS Closed-Loop Digital Twin Trace Exporter -->',
        '<routes xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="http://sumo.dlr.de/xsd/routes_file.xsd">',
    ]

    # 1. Vehicle Types
    lines.append('    <!-- 1. Calibrated Vehicle Type Specifications -->')
    for spec in CATALOG_VEHICLE_TYPES.values():
        r, g, b, a = spec.color
        color_str = f"{r},{g},{b}"
        lines.append(
            f'    <vType id="{spec.type_id}" vClass="{spec.vclass}" length="{spec.length:.1f}" '
            f'maxSpeed="{spec.max_speed:.2f}" accel="{spec.accel:.1f}" decel="{spec.decel:.1f}" '
            f'color="{color_str}"/>'
        )

    # 2. Standard Approaches and Routes
    lines.append('\n    <!-- 2. Standard Intersection Routes (Through & Left-Turn) -->')
    for app, inc in APPROACH_EDGES.items():
        through_out, left_out = APPROACH_TURNS[app]
        lines.append(f'    <route id="route_{app}_through" edges="{inc} {through_out}"/>')
        lines.append(f'    <route id="route_{app}_left" edges="{inc} {left_out}"/>')

    # 3. Individual Vehicles sorted by departure timestamp
    lines.append('\n    <!-- 3. Recorded Camera Vehicle Departures -->')
    sorted_deps = sorted(departures, key=lambda d: float(d.get("depart_time", 0.0)))

    for i, dep in enumerate(sorted_deps):
        depart_time = max(0.0, float(dep.get("depart_time", 0.0)))
        if duration is not None and depart_time > duration:
            continue

        raw_app = dep.get("approach", "N")
        app = normalize_approach(raw_app)
        raw_cls = dep.get("class_name", "car")
        canonical_cls = config.canonical_class(raw_cls)
        vtype = (
            CATALOG_VEHICLE_TYPES[canonical_cls].type_id
            if canonical_cls in CATALOG_VEHICLE_TYPES
            else CATALOG_VEHICLE_TYPES["car"].type_id
        )

        turn = dep.get("turn", "through")
        route_id = f"route_{app}_left" if turn == "left" else f"route_{app}_through"
        track_id = dep.get("track_id", i + 1)
        veh_id = f"trace_{app}_{track_id}_{i}"

        lines.append(
            f'    <vehicle id="{veh_id}" type="{vtype}" route="{route_id}" '
            f'depart="{depart_time:.2f}" departLane="best" departSpeed="max"/>'
        )

    lines.append('</routes>\n')
    return "\n".join(lines)


def export_trace_routes(
    departures: Sequence[dict[str, Any]],
    out_path: Path,
    duration: Optional[float] = None,
) -> Path:
    """Write departures to a SUMO .rou.xml file."""
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    xml_content = generate_trace_routes_xml(departures, duration=duration)
    out_path.write_text(xml_content, encoding="utf-8")
    logger.info(f"Exported {len(departures)} trace vehicles to {out_path}")
    return out_path


def create_trace_sumocfg(
    net_path: Path,
    rou_path: Path,
    out_path: Path,
    duration: float = 600.0,
    seed: int = 42,
) -> Path:
    """Generate a .sumocfg configuration referencing the trace routes file."""
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    net_rel = net_path.name if net_path.parent == out_path.parent else str(net_path)
    rou_rel = rou_path.name if rou_path.parent == out_path.parent else str(rou_path)

    cfg = f"""<?xml version="1.0" encoding="UTF-8"?>
<configuration>
    <input>
        <net-file value="{net_rel}"/>
        <route-files value="{rou_rel}"/>
    </input>
    <time>
        <begin value="0"/>
        <end value="{duration:.0f}"/>
        <step-length value="1"/>
    </time>
    <processing>
        <time-to-teleport value="-1"/>
    </processing>
    <random_number>
        <seed value="{seed}"/>
    </random_number>
</configuration>
"""
    out_path.write_text(cfg, encoding="utf-8")
    return out_path
