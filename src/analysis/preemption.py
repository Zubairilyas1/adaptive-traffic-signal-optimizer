"""Emergency Vehicle Preemption (EVP) & Priority Green Wave Engine.

Detects approaching emergency vehicles (ambulances, fire engines, police cruisers)
and triggers high-priority safe green-wave preemption through the NEMA actuation layer.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

from src import config

logger = logging.getLogger(__name__)

# Classes recognized as priority emergency vehicles
EMERGENCY_CLASSES: frozenset[str] = frozenset({
    "ambulance",
    "fire_truck",
    "fire truck",
    "fire engine",
    "police",
    "police car",
    "emergency",
})


class PreemptionState(Enum):
    """Operational states of the emergency preemption coordinator."""

    IDLE = "idle"  # Normal signal operation (PPO / Actuated / Webster)
    CLEARING = "clearing"  # Terminating conflicting green with safety clearance
    PREEMPTING = "preempting"  # Holding emergency green corridor open
    RECOVERING = "recovering"  # Safe post-preemption baseline transition


@dataclass
class PreemptionRequest:
    """Active preemption call generated by confirmed emergency vehicle detection."""

    track_id: int
    vehicle_class: str
    approach: str
    speed_km_h: float
    distance_to_stopline_m: float
    eta_seconds: float
    timestamp: float
    confirmed: bool = True

    def to_dict(self) -> dict[str, Any]:
        return {
            "track_id": self.track_id,
            "vehicle_class": self.vehicle_class,
            "approach": self.approach,
            "speed_km_h": round(self.speed_km_h, 1),
            "distance_to_stopline_m": round(self.distance_to_stopline_m, 1),
            "eta_seconds": round(self.eta_seconds, 1),
            "timestamp": round(self.timestamp, 2),
            "confirmed": self.confirmed,
        }


class EmergencyPreemptionDetector:
    """Perception-level emergency vehicle tracker with temporal confirmation filtering."""

    def __init__(
        self,
        min_consecutive_frames: int = 3,
        min_approaching_speed_km_h: float = 12.0,
        max_preemption_distance_m: float = 80.0,
    ) -> None:
        self.min_consecutive_frames = min_consecutive_frames
        self.min_approaching_speed_km_h = min_approaching_speed_km_h
        self.max_preemption_distance_m = max_preemption_distance_m

        # track_id -> dict of tracking state
        self._candidates: dict[int, dict[str, Any]] = {}
        self.active_requests: dict[int, PreemptionRequest] = {}

    def is_emergency_class(self, class_name: str) -> bool:
        """Check if vehicle class qualifies for emergency priority."""
        clean = str(class_name).lower().strip().replace("-", "_")
        return clean in EMERGENCY_CLASSES or any(k in clean for k in ("ambulance", "fire", "police"))

    def update(
        self,
        detections: Iterable[Any],
        timestamp: float,
        ipm_transformer: Optional[Any] = None,
    ) -> list[PreemptionRequest]:
        """Evaluate detections for approaching emergency vehicles.

        Requires consecutive frames of approaching velocity to eliminate false alarms.
        """
        current_frame_tracks: set[int] = set()
        new_confirmed_requests: list[PreemptionRequest] = []

        for det in detections:
            track_id = getattr(det, "track_id", None)
            if isinstance(det, dict):
                track_id = det.get("track_id")
                class_name = det.get("class_name", "")
                bbox = det.get("bbox")
                speed_km_h = float(det.get("speed_km_h", 0.0))
                approach = str(det.get("approach", det.get("lane_id", "N")))
            else:
                class_name = getattr(det, "class_name", "")
                bbox = getattr(det, "bbox", None)
                speed_km_h = float(getattr(det, "speed_km_h", 0.0))
                approach = str(getattr(det, "approach", getattr(det, "lane_id", "N")))

            if track_id is None or not self.is_emergency_class(class_name):
                continue

            tid = int(track_id)
            current_frame_tracks.add(tid)

            # Estimate distance to stopline
            dist_m = 30.0
            if ipm_transformer is not None and bbox is not None:
                try:
                    if hasattr(ipm_transformer, "get_transformer"):
                        trans = ipm_transformer.get_transformer(approach)
                        dist_m = trans.distance_to_stopline_meters(bbox)
                    else:
                        dist_m = ipm_transformer.distance_to_stopline_meters(bbox)
                except Exception:
                    dist_m = 30.0

            # Compute ETA
            speed_m_s = max(1.0, speed_km_h / 3.6) if speed_km_h > 0 else 8.33  # ~30 km/h default
            eta_s = dist_m / speed_m_s

            if tid not in self._candidates:
                self._candidates[tid] = {
                    "consecutive": 1,
                    "class_name": class_name,
                    "approach": approach,
                    "first_seen": timestamp,
                    "last_dist": dist_m,
                    "speed_km_h": speed_km_h,
                }
            else:
                cand = self._candidates[tid]
                cand["consecutive"] += 1
                cand["last_dist"] = dist_m
                cand["speed_km_h"] = speed_km_h
                cand["approach"] = approach

                # Confirm preemption request once temporal threshold is reached
                if cand["consecutive"] >= self.min_consecutive_frames and tid not in self.active_requests:
                    req = PreemptionRequest(
                        track_id=tid,
                        vehicle_class=class_name,
                        approach=approach,
                        speed_km_h=speed_km_h,
                        distance_to_stopline_m=dist_m,
                        eta_seconds=eta_s,
                        timestamp=timestamp,
                        confirmed=True,
                    )
                    self.active_requests[tid] = req
                    new_confirmed_requests.append(req)
                    logger.warning(
                        f"EMERGENCY PREEMPTION TRIGGERED: {class_name} (ID: {tid}) approaching on {approach} "
                        f"(ETA: {eta_s:.1f}s, Dist: {dist_m:.1f}m)"
                    )

        # Purge disappeared candidates
        disappeared = set(self._candidates.keys()) - current_frame_tracks
        for tid in disappeared:
            del self._candidates[tid]
            if tid in self.active_requests:
                del self.active_requests[tid]

        return new_confirmed_requests


class PreemptionCoordinator:
    """Coordinates signal clearance, emergency green holding, and recovery."""

    def __init__(
        self,
        yellow_clearance_s: float = 2.5,
        all_red_clearance_s: float = 1.0,
        post_passage_hold_s: float = 2.0,
        max_preempt_duration_s: float = 45.0,
    ) -> None:
        self.yellow_clearance_s = yellow_clearance_s
        self.all_red_clearance_s = all_red_clearance_s
        self.post_passage_hold_s = post_passage_hold_s
        self.max_preempt_duration_s = max_preempt_duration_s

        self.state: PreemptionState = PreemptionState.IDLE
        self.active_request: Optional[PreemptionRequest] = None
        self.target_phase: int = 0  # 0: North-South, 1: East-West
        self.state_time_s: float = 0.0
        self.total_preemptions: int = 0

    def trigger_preemption(self, req: PreemptionRequest, current_phase: int) -> None:
        """Initiate emergency priority sequence for requested approach."""
        self.active_request = req
        # Normalize approach to phase: North/South -> 0, East/West -> 1
        clean_app = str(req.approach).strip().upper()
        self.target_phase = 1 if (clean_app.startswith("E") or clean_app.startswith("W")) else 0

        if current_phase == self.target_phase:
            # Target corridor is already green! Immediately lock into PREEMPTING state
            self.state = PreemptionState.PREEMPTING
            self.state_time_s = 0.0
            logger.info(f"Target corridor already GREEN for emergency vehicle: Phase {self.target_phase} locked.")
        else:
            # Must safely terminate cross-street green
            self.state = PreemptionState.CLEARING
            self.state_time_s = 0.0
            logger.info(f"Initiating fast safety clearance to yield to emergency corridor Phase {self.target_phase}.")

        self.total_preemptions += 1

    def step(self, dt: float = 1.0) -> tuple[PreemptionState, Optional[int], str]:
        """Advance preemption timer and return (state, override_phase, status_message).

        Returns:
            (PreemptionState, override_phase_or_None, explanation)
        """
        if self.state == PreemptionState.IDLE:
            return PreemptionState.IDLE, None, "No active emergency preemption"

        self.state_time_s += dt

        # State 1: CLEARING conflicting phase
        if self.state == PreemptionState.CLEARING:
            if self.state_time_s < self.yellow_clearance_s:
                return (
                    PreemptionState.CLEARING,
                    None,
                    f"EMERGENCY CLEARANCE: Fast Yellow ({self.state_time_s:.1f}s / {self.yellow_clearance_s:.1f}s)",
                )
            elif self.state_time_s < (self.yellow_clearance_s + self.all_red_clearance_s):
                return (
                    PreemptionState.CLEARING,
                    None,
                    "EMERGENCY CLEARANCE: All-Red Intersection Lockout",
                )
            else:
                # Clearance complete -> Open emergency green corridor
                self.state = PreemptionState.PREEMPTING
                self.state_time_s = 0.0
                corridor = "North-South" if self.target_phase == 0 else "East-West"
                return (
                    PreemptionState.PREEMPTING,
                    self.target_phase,
                    f"EMERGENCY GREEN OPENED: Priority for {corridor} corridor",
                )

        # State 2: PREEMPTING (Holding Green for Emergency Corridor)
        if self.state == PreemptionState.PREEMPTING:
            corridor = "North-South" if self.target_phase == 0 else "East-West"
            req_cls = self.active_request.vehicle_class.upper() if self.active_request else "EMERGENCY VEHICLE"

            # Check if preemption timed out or vehicle passed
            if self.state_time_s >= self.max_preempt_duration_s:
                self.state = PreemptionState.RECOVERING
                self.state_time_s = 0.0
                return (
                    PreemptionState.RECOVERING,
                    self.target_phase,
                    f"Emergency preemption max timeout ({self.max_preempt_duration_s:.0f}s) reached -> Initiating recovery",
                )

            return (
                PreemptionState.PREEMPTING,
                self.target_phase,
                f"🚨 {req_cls} PREEMPTION ACTIVE: Holding {corridor} GREEN ({self.state_time_s:.1f}s)",
            )

        # State 3: RECOVERING (Restoring normal cycle smoothly)
        if self.state == PreemptionState.RECOVERING:
            if self.state_time_s >= self.post_passage_hold_s:
                self.state = PreemptionState.IDLE
                self.active_request = None
                self.state_time_s = 0.0
                return (
                    PreemptionState.IDLE,
                    None,
                    "Preemption sequence concluded -> Resumed autonomous adaptive control",
                )
            return (
                PreemptionState.RECOVERING,
                self.target_phase,
                f"Post-passage safety hold ({self.state_time_s:.1f}s / {self.post_passage_hold_s:.1f}s)",
            )

        return PreemptionState.IDLE, None, ""

    def cancel(self) -> None:
        """Manually abort preemption and restore normal operation."""
        self.state = PreemptionState.IDLE
        self.active_request = None
        self.state_time_s = 0.0
